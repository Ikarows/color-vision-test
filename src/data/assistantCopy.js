// 随机取一条
export function pickCopy(list) {
  return list[Math.floor(Math.random() * list.length)];
}

// 占位符替换:{count} {total} {last} {streak} {minutes}
export function fillCopy(tpl, vars = {}) {
  return tpl.replace(/\{(\w+)\}/g, (m, k) =>
    vars[k] !== undefined ? vars[k] : m,
  );
}
